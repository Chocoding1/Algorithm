SELECT UGU.USER_ID, UGU.NICKNAME, UGB.TOTAL_SALES
FROM USED_GOODS_USER AS UGU
JOIN (SELECT UGB.WRITER_ID, SUM(UGB.PRICE) AS TOTAL_SALES
     FROM USED_GOODS_BOARD AS UGB
     WHERE UGB.STATUS = 'DONE'
     GROUP BY UGB.WRITER_ID
        HAVING SUM(UGB.PRICE) >= 700000) AS UGB
    ON UGU.USER_ID = UGB.WRITER_ID
ORDER BY UGB.TOTAL_SALES;
