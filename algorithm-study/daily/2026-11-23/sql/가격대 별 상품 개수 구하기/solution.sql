SELECT P2.PRICE_GROUP AS PRICE_GROUP, COUNT(*) AS PRODUCTS
FROM PRODUCT AS P1
JOIN (SELECT PRODUCT_ID, FLOOR(PRICE / 10000) * 10000 AS PRICE_GROUP
        FROM PRODUCT) AS P2
    ON P1.PRODUCT_ID = P2.PRODUCT_ID
GROUP BY P2.PRICE_GROUP
ORDER BY PRICE_GROUP ASC;
