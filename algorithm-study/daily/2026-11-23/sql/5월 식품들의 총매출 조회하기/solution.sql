SELECT FP.PRODUCT_ID, FP.PRODUCT_NAME, (FP.PRICE * FO.TOTAL_AMOUNT) AS TOTAL_SALES
FROM FOOD_PRODUCT AS FP
JOIN (SELECT PRODUCT_ID, SUM(AMOUNT) AS TOTAL_AMOUNT
        FROM FOOD_ORDER
        WHERE PRODUCE_DATE >= '2022-05-01'
            AND PRODUCE_DATE < '2022-06-01'
        GROUP BY PRODUCT_ID) AS FO
    ON FP.PRODUCT_ID = FO.PRODUCT_ID
ORDER BY TOTAL_SALES DESC, FP.PRODUCT_ID ASC;
