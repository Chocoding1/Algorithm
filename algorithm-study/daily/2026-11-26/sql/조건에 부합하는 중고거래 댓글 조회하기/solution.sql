SELECT UGB.TITLE, UGB.BOARD_ID, UGR.REPLY_ID, UGR.WRITER_ID, UGR.CONTENTS, UGR.CREATED_DATE
FROM USED_GOODS_REPLY AS UGR
JOIN (SELECT BOARD_ID, TITLE
      FROM USED_GOODS_BOARD
      WHERE CREATED_DATE >= '2022-10-01'
        AND CREATED_DATE < '2022-11-01') AS UGB
    ON UGR.BOARD_ID = UGB.BOARD_ID
ORDER BY UGR.CREATED_DATE, UGB.TITLE;
